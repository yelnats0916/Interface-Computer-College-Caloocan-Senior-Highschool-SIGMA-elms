const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('js/subject-editor.js','utf8');
const start = source.indexOf('    function canAdminEditTeacherScope()');
const end = source.indexOf('    function resolveSubjectItemSection',start);
let user = {role:'Master Admin',id:'admin'};
let teacher = false;
const window = {activeCurriculumScope:'teacher-1',activeCurriculumScopeLabel:'Ana Bautista (Einstein)',subjectEditorOptions:{standalone:true}};
const context = {window,isCurrentEditorTeacher:()=>teacher,getCurrentEditorUser:()=>user,normalizeSubjectAuthorRole:value=>value};
vm.runInNewContext(source.slice(start,end),context);
assert.equal(window.isCurrentViewOnlyScope(),false);
assert.equal(window.isCurrentUserAuthor('teacher-1','Ana Bautista','Teacher'),true);
assert.equal(window.isCurrentUserAuthor('teacher-2','Someone Else','Teacher'),false);
user = {role:'Admin',permissions:{subjectAuthority:false}};
assert.equal(window.isCurrentUserAuthor('teacher-1','Ana Bautista','Teacher'),false);
assert.equal(window.isCurrentViewOnlyScope(),true);
user = {role:'Teacher',id:'teacher-2',firstName:'Other',lastName:'Teacher'}; teacher = true;
assert.equal(window.isCurrentUserAuthor('teacher-1','Ana Bautista','Teacher'),false);
assert.equal(window.isCurrentUserAuthor('admin','Admin','Admin'),false);
console.log('PASS: authorized admin edits selected teacher scope; other teacher scopes and denied admins stay protected; teacher restrictions preserved.');
