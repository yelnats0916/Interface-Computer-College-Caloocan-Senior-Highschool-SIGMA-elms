const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'js/student-insight-view.js'), 'utf8');
const start = source.indexOf('    window.getInsightPreviewLineCount =');
const end = source.indexOf('\n    };', start) + 7;
const context = { window: {} };
vm.runInNewContext(source.slice(start, end), context);
const fit = context.window.getInsightPreviewLineCount;
assert.equal(fit(117, 18), 6);
assert.equal(fit(160, 18), 8);
assert.equal(fit(54, 18), 3);
assert.equal(fit(201, 18), 11);
const css = fs.readFileSync(path.join(root, 'css/sigma-analytics.css'), 'utf8');
assert.match(css, /-webkit-line-clamp: var\(--sigma-preview-lines, unset\)/);
assert.match(css, /\.sigma-insight-preview \{ flex: 1 1 0;/);
assert.ok(!css.includes('max-height: 72px'));
console.log('Preview truncation follows available card height instead of a fixed four-line limit');
