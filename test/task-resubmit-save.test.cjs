const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const page = await browser.newPage();
        await page.route('http://fixture.test/**', route => route.fulfill({ body: '<html><body></body></html>', contentType: 'text/html' }));
        await page.goto('http://fixture.test/student.html');
        await page.addScriptTag({ path: 'js/shared-components.js' });
        const result = await page.evaluate(() => {
            const realGetSubmission = window.getStudentAssessmentSubmission;
            const student = { id: 's1', name: 'Student', section: 'Rizal' };
            const assessment = { id: 'task1', title: 'Task 1', type: 'assignment', maxScore: 100 };
            const previous = { studentId: 's1', section: 'Rizal', status: 'Submitted', submittedAt: '2026-10-12T09:00:00Z', fileName: 'first.txt', files: [{ name: 'first.txt', type: 'txt', url: '' }], attemptsUsed: 1, score: 90 };
            window.getLoggedInStudentUser = () => student;
            window.getCurrentTopicAssessment = () => assessment;
            window.getStudentSubmissionStorageKey = () => 'sigma_sub_s1_prog_task1';
            window.isAssessmentLateSubmissionAllowed = () => true;
            window.resolveStudentReleaseSection = () => 'Rizal';
            window.currentTopicState = { subjectId: 'prog', topicIdx: 0, selectedSection: 'Rizal' };
            window.showToast = () => {};
            window.getUnifiedSubjectAliases = () => ['prog', 'Computer Programming 1'];
            localStorage.setItem('sigma_student_assessment_submissions', JSON.stringify({ s1: { prog_sec_rizal_mat_task1: { ...previous, id: 'task1', materialId: 'task1', title: 'Task 1', teacherSaved: true, status: 'Graded' } } }));
            localStorage.setItem('sigma_extra_attempts_s1_Computer Programming 1_0_assessments_0', '1');
            window.performStudentAssessmentSubmit('prog', 'assessments', 0, [{ name: 'second.txt', url: '', size: 10 }], 2, '', 0, 'task1');
            const saved = JSON.parse(localStorage.getItem('sigma_sub_s1_prog_task1'));
            const staleGrade = { ...previous, id: 'task1', materialId: 'task1', title: 'Task 1', teacherSaved: true, status: 'Graded', extraAttempts: 1, allowResubmitGranted: true };
            localStorage.setItem('sigma_student_assessment_submissions', JSON.stringify({ s1: { prog_sec_rizal_mat_task1: staleGrade } }));
            window.getStudentAssessmentSubmission = realGetSubmission;
            const resolved = realGetSubmission('prog', 'assessments', 0, 0, assessment, student);
            window._studentViewSubmissionMode = true;
            window.getStudentAssessmentReleaseStatus = () => ({ isLocked: false, isHidden: false, isUnreleased: false });
            const html = window.renderSharedAssessmentsTabHtml({ assessments: [assessment], activeIdx: 0, subjectId: 'prog', topicIdx: 0, section: 'Rizal', tab: 'assessments', role: 'student' });
            return { saved, resolved, html, extra: window.getAssessmentExtraAttempts('prog', 0, 'assessments', 0, student, resolved) };
        });
        assert.equal(result.saved.attemptsUsed, 2);
        assert.equal(result.saved.history.length, 2);
        assert.equal(result.saved.history[0].fileName, 'first.txt');
        assert.equal(result.saved.history[1].fileName, 'second.txt');
        assert.equal(result.extra, 0);
        assert.equal(result.resolved.attemptsUsed, 2);
        assert.equal(result.resolved.history.length, 2);
        assert.equal(result.resolved.fileName, 'second.txt');
        assert.equal(result.resolved.status, 'Submitted');
        assert.equal(result.resolved.allowResubmitGranted, false);
        assert.match(result.html, /id="submission-attempt-select"/);
        assert.match(result.html, /Attempt 2 - Latest/);
        assert.doesNotMatch(result.html, />\s*Resubmit\s*</);
        assert.match(result.html, /1 \(\+1\)/);
        const recovered = await page.evaluate(() => {
            localStorage.clear();
            window._sharedAssessmentSubmissionsMemoryCache = {};
            window.getSharedAssessmentSubmissionsStorage = () => ({});
            window.findAssessmentSubmittedWork = () => null;
            const student = { id: 's1', name: 'Student', section: 'Rizal' };
            const assessment = { id: 'task1', title: 'Task 1', type: 'assignment' };
            const old = { materialId: 'task1', studentId: 's1', subjectId: 'Computer Programming 1', section: 'Rizal', title: 'Task 1', status: 'Submitted', fileName: 'E02_01TP.docx', submittedAt: '2026-10-01T09:00:00Z', attemptsUsed: 1 };
            const latest = { ...old, subjectId: 'prog', fileName: 'latest.pdf', submittedAt: '2026-10-13T09:00:00Z' };
            localStorage.setItem('sigma_sub_Computer Programming 1_top_0_mat_task1_std_s1', JSON.stringify(old));
            localStorage.setItem('sigma_sub_s1_prog_top_0_mat_task1', JSON.stringify(latest));
            localStorage.setItem('sigma_sub_prog_top_0_mat_task1_std_s1', JSON.stringify(latest));
            localStorage.setItem('sigma_sub_Computer Programming 1_top_0_mat_task1_std_s2', JSON.stringify({ ...old, studentId: 's2', fileName: 'other-student.docx' }));
            return window.getStudentAssessmentSubmission('prog', 'assessments', 0, 0, assessment, student);
        });
        assert.equal(recovered.history.length, 2);
        assert.equal(recovered.history[0].fileName, 'E02_01TP.docx');
        assert.equal(recovered.history[1].fileName, 'latest.pdf');
        assert.equal(recovered.attemptsUsed, 2);
        const statusOnly = await page.evaluate(() => {
            localStorage.clear();
            window._studentAssessmentDetailsCache.clear();
            window.getStudentAssessmentSubmission = () => null;
            window.getEffectiveAssessmentStatusAndScore = () => ({ status: '', score: '' });
            window.resolveGradebookScoreColumn = () => null;
            window.gradebookAttendanceMark = () => ({ code: 'E', name: 'Excuse', tone: 'excuse' });
            window.findAssessmentSubmittedWork = () => null;
            window.resolveNoDeadlineAssessment = () => false;
            window.readScorePanelPoints = () => null;
            window.readStudentVisibleGradebookScore = () => null;
            return window.resolveStudentAssessmentSubmissionDetails({ id: 'task2', title: 'Task 2 - Basic Syntax and Data Types Quiz', category: 'assignment', maxScore: 100 }, 'prog', 0, 1, 'Rizal', { id: 's1', name: 'Student', section: 'Rizal' });
        });
        assert.equal(statusOnly.attendanceTone, 'excuse');
        assert.equal(statusOnly.statusName, 'Excuse');
        assert.equal(statusOnly.turnedIn, false);
        assert.equal(statusOnly.numericScore, null);
        console.log('PASS: task resubmit resolves assessment ID, retains first attempt, saves second, and consumes alias grants.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
