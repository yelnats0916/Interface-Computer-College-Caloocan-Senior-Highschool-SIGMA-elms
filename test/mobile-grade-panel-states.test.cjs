function classList(initial = []) {
    const set = new Set(initial);
    return { contains: c => set.has(c), add: (...cs) => cs.forEach(c => set.add(c)), remove: (...cs) => cs.forEach(c => set.delete(c)), toggle(c) { if (set.has(c)) { set.delete(c); return false; } set.add(c); return true; } };
}
const icon = {};
const maximize = { style: { setProperty(key, value, priority) { this[key] = value; this.priority = priority; } } };
const minimize = { querySelector: () => icon, setAttribute(k, v) { this[k] = v; } };
const chevron = {};
const toggle = { setAttribute(k, v) { this[k] = v; } };
const header = {};
const controls = { classList: classList(['hidden']) };
const section = { classList: classList(['hidden']) };
const card = { classList: classList(['is-collapsed', 'is-desktop-collapsed']), querySelector: selector => ({ '.mobile-grade-maximize-btn': maximize, '.mobile-grade-minimize-btn': minimize, '.desktop-grading-header': header, '.desktop-grading-toggle-btn': toggle, '#desktop-grading-panel-chevron': chevron, '.desktop-grading-collapsible-section': section, '.desktop-grading-collapsible-controls': controls })[selector] };
const listeners = {};
const window = { innerWidth: 390, matchMedia: () => ({ addEventListener(type, fn) { listeners.mode = fn; } }), addEventListener(type, fn) { listeners[type] = fn; } };
const document = { querySelector: () => card, getElementById: () => null };
