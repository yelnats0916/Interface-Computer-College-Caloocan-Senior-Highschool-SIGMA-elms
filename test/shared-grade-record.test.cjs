const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert');
const sharedAssets = html => Array.from(html.matchAll(/(?:src|href)="((?:js|css)\/(?:sigma-analytics|shared-grade-record|shared-components|offline-assessments|excel-export)\.(?:js|css)\?v=[^"]+)"/g), match => match[1]).sort();
assert.deepStrictEqual(sharedAssets(fs.readFileSync('admin.html', 'utf8')), sharedAssets(fs.readFileSync('teacher.html', 'utf8')), 'Admin and teacher grade assets must stay in sync');
(async () => {
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const page = await browser.newPage();
        await page.route('http://record.test/**', route => route.fulfill({ contentType: 'text/html', body: '<div id="admin-grades-shared-navbar"></div><div id="admin-grades-quarters-wrapper"><button>Q1</button><button>Q2</button></div><div id="admin-gradebook-workspace-content"></div>' }));
        await page.goto('http://record.test/');
        await page.evaluate(css => { const style = document.createElement('style'); style.textContent = css; document.head.append(style); }, fs.readFileSync('css/shared-grade-record.css', 'utf8'));
        await page.evaluate(() => {
            window.sigmaGradesState = { selectedSubjectSection: { subject: 'Programming', sectionName: 'Rizal' }, activeQuarter: 1, currentView: 'ww' };
            window.getActiveSchoolYearRecord = () => ({ name: '2026-2027' });
            window.renderAdminGradebookWorkspace = () => { window._gradebookExportSnapshot = { subject: 'Programming', section: 'Rizal', quarter: window.sigmaGradesState.activeQuarter, teacher: { id: 't1' }, rows: [{ student: { id: '01', name: 'Juan' }, quarterly: window.sigmaGradesState.activeQuarter === 1 ? 85 : 90 }, { student: { id: '02', name: 'Herald' }, quarterly: null }] }; };
        });
        await page.evaluate(fs.readFileSync('js/shared-grade-record.js', 'utf8'));
        for (const width of [1440, 390]) {
            await page.evaluate(() => localStorage.clear());
            await page.setViewportSize({ width, height: 900 });
            await page.evaluate(() => window.openSharedGradeRecord());
            assert.equal(await page.locator('.record-share').isDisabled(), true);
            assert.equal(await page.locator('.record-actions i').count(), 0);
            assert.equal(await page.locator('.record-back').textContent(), 'Back');
            assert.equal(await page.locator('#record-note').isVisible(), true);
            assert.equal(await page.locator('.record-comment-row').isVisible(), false);
            await page.locator('.record-add-comment').click();
            assert.equal(await page.locator('.record-comment-row').isVisible(), true);
            assert.equal(await page.locator('.record-add-comment').isVisible(), false);
            assert.equal(await page.locator('.sigma-comment-send-btn').isDisabled(), false);
            await page.locator('.sigma-comment-textarea').fill('Please review this quarter.');
            await page.locator('.sigma-comment-textarea').press('Enter');
            assert.match(await page.locator('.record-comment-history').textContent(), /Please review this quarter/);
            assert.equal(await page.locator('.record-comment-count').textContent(), '1');
            assert.equal(await page.locator('.sigma-comment-delete-btn i.fa-trash-can').count(), 1);
            await page.locator('.record-posted-comment').hover();
            assert.equal(await page.locator('.sigma-comment-delete-btn').isVisible(), true);
            await page.evaluate(() => { window.openAskingPanel = options => { window.testDeleteConfirmation = options; }; });
            await page.locator('.sigma-comment-delete-btn').click();
            assert.equal(await page.locator('.record-posted-comment').count(), 1);
            assert.equal(await page.evaluate(() => window.testDeleteConfirmation.title), 'Delete Comment');
            await page.evaluate(() => window.testDeleteConfirmation.onConfirm());
            assert.equal(await page.locator('.record-posted-comment').count(), 0);
            assert.equal(await page.locator('.record-comment-count').count(), 0);
            assert.equal(await page.locator('.record-add-comment').isVisible(), true);
            await page.locator('#record-note').fill('Personal reminder');
            await page.locator('.record-note-enter').click();
            assert.equal(await page.locator('.record-note-enter').textContent(), 'Edit Notes');
            assert.equal(await page.locator('#record-note').isVisible(), false);
            assert.equal(await page.locator('.record-note-delete').isVisible(), true);
            assert.equal(await page.locator('.record-saved-note').textContent(), 'Personal reminder');
            assert.equal(await page.locator('#record-note').inputValue(), '');
            assert.equal(await page.evaluate(() => Object.keys(localStorage).filter(key => key.includes('sigma-grade-personal-notes')).length > 0), true);
            const mainBox = await page.locator('.record-main').boundingBox();
            const commentsBox = await page.locator('.record-sidebar').boundingBox();
            const actionsBox = await page.locator('.record-actions').boundingBox();
            const tableBox = await page.locator('.record-table-scroll').boundingBox();
            const statusBox = await page.locator('.record-status').boundingBox();
            assert(statusBox.y >= tableBox.y + tableBox.height);
            assert(actionsBox.y >= tableBox.y + tableBox.height);
            assert(Math.abs(actionsBox.x + actionsBox.width - mainBox.x - mainBox.width) < 2);
            if (width > 760) assert(commentsBox.x > mainBox.x + mainBox.width);
            else assert(commentsBox.y > mainBox.y);
            assert.match(await page.locator('.record-status').textContent(), /missing grade/);
            await page.screenshot({ path: `${require('os').tmpdir()}/sigma-share-record-${width}.png`, fullPage: true });
            await page.locator('.record-update').click();
            assert.match(await page.locator('.record-status').textContent(), /Quarter Updated/);
            assert.equal(await page.locator('.record-draft-cell').count(), 0);
            assert.equal(await page.locator('.record-share').isDisabled(), false);
            await page.locator('.record-share').click();
            assert.match(await page.locator('.record-error').textContent(), /No grades have been sent/);
            await page.evaluate(() => {
                const original = window.renderAdminGradebookWorkspace;
                window.renderAdminGradebookWorkspace = () => { original(); window._gradebookExportSnapshot.rows[0].quarterly = 86; };
                window.openSharedGradeRecord();
                window.renderAdminGradebookWorkspace = original;
            });
            assert.equal(await page.locator('.record-draft-cell').count(), 1);
            assert.equal(await page.locator('.record-share').isDisabled(), true);
            await page.evaluate(() => window.openSharedGradeRecord());
            assert.equal(await page.locator('.record-update').isDisabled(), true);
            await page.evaluate(() => { window.sigmaGradesState.activeQuarter = 2; window.openSharedGradeRecord(); });
            assert.match(await page.locator('tbody tr').first().textContent(), /85.*90.*88/);
            await page.locator('.record-update').click();
            await page.evaluate(() => { window.sigmaGradesState.activeQuarter = 1; });
        }
        const bootstrap = await page.evaluate(() => `window.sigmaGradesState=${JSON.stringify(window.sigmaGradesState)};window.getActiveSchoolYearRecord=${window.getActiveSchoolYearRecord.toString()};window.renderAdminGradebookWorkspace=${window.renderAdminGradebookWorkspace.toString()};`);
        await page.addInitScript({ content: bootstrap + fs.readFileSync('js/shared-grade-record.js', 'utf8') });
        await page.reload();
        await page.waitForSelector('.shared-grade-record');
        assert.match(page.url(), /gradebook:share-record$/);
        for (let refresh = 0; refresh < 3; refresh++) {
            await page.reload();
            await page.waitForSelector('.shared-grade-record');
            assert.match(page.url(), /gradebook:share-record$/);
        }
        assert.match(await page.locator('.record-heading').textContent(), /Programming.*Rizal/);
        await page.locator('.record-back').click();
        assert.match(page.url(), /#grades:gradebook$/);
        await page.goto('http://record.test/admin.html#school-grades:gradebook');
        await page.evaluate(() => window.openSharedGradeRecord());
        assert.match(page.url(), /#school-grades:gradebook:share-record$/);
        await page.reload();
        await page.waitForSelector('.shared-grade-record');
        assert.match(page.url(), /#school-grades:gradebook:share-record$/);
        await page.locator('.record-back').click();
        assert.match(page.url(), /#school-grades:gradebook$/);
        console.log('Share record: draft/save, retained quarters, missing grades, text-only actions and desktop/mobile passed.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
