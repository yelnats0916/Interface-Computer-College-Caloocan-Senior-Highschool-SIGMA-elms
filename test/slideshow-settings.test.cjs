const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..');
(async () => {
    const browser = await chromium.launch({ headless: true, channel: 'chrome' });
    try {
        const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
        const html = fs.readFileSync(path.join(root, 'admin.html'), 'utf8');
        const start = html.indexOf('                <div id="brand-slides-panel"');
        const panel = html.slice(start, html.indexOf('                <!-- Card 3: Welcome Panel Banner -->', start));
        await page.route('http://sigma.test/**', route => {
            const url = new URL(route.request().url());
            if (url.pathname === '/js/slideshow-settings.js') return route.fulfill({ contentType: 'application/javascript', body: fs.readFileSync(path.join(root, 'js/slideshow-settings.js')) });
            if (url.pathname.startsWith('/image/')) return route.fulfill({ contentType: 'image/jpeg', body: fs.readFileSync(path.join(root, decodeURIComponent(url.pathname).slice(1))) });
            return route.fulfill({ contentType: 'text/html', body: panel });
        });
        async function load() {
            await page.goto('http://sigma.test/admin.html');
            await page.addStyleTag({ path: path.join(root, 'css/forms.css') });
            await page.addStyleTag({ path: path.join(root, 'css/settings-view.css') });
            await page.addScriptTag({ url: 'http://sigma.test/js/slideshow-settings.js' });
        }
        await load();
        assert.equal(await page.locator('#slideshow-count').textContent(), '5 of 7 slides');
        assert.equal(await page.locator('#slideshow-count').isVisible(), false);
        assert.equal(await page.locator('#slideshow-position').evaluate(node => getComputedStyle(node).color), 'rgba(0, 0, 0, 0.45)');
        assert.equal(await page.locator('#slideshow-grid').isVisible(), false);
        await page.getByRole('button', { name: 'Manage Slideshow' }).click();
        assert.equal(await page.locator('#slideshow-count').isVisible(), true);
        assert.equal(await page.locator('#slideshow-count').evaluate(node => getComputedStyle(node).color), 'rgb(0, 0, 0)');
        assert.equal(await page.locator('#slideshow-count').evaluate(node => getComputedStyle(node).fontSize), '16px');
        const countBounds = await page.locator('#slideshow-count').boundingBox();
        const cancelBounds = await page.locator('#slideshow-cancel').boundingBox();
        assert.ok(Math.abs(countBounds.y + countBounds.height / 2 - cancelBounds.y - cancelBounds.height / 2) < 1);
        assert.equal(await page.locator('.slideshow-tile').count(), 5);
        assert.equal(await page.getByRole('button', { name: /Move left|Move right/ }).count(), 0);
        const previewMode = page.locator('[data-slide-mode="preview"]');
        assert.equal(await previewMode.evaluate(node => getComputedStyle(node).color), 'rgba(0, 0, 0, 0.45)');
        await previewMode.hover();
        assert.equal(await previewMode.evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(226, 232, 240)');
        assert.equal(await page.locator('#slideshow-restore').isVisible(), false);
        assert.equal(await page.locator('.slideshow-tile figcaption').first().textContent(), 'Slide 1 \u2014 First');
        assert.equal(await page.locator('.slideshow-tile-card figcaption').count(), 0);
        const cardBounds = await page.locator('.slideshow-tile-card').first().boundingBox();
        const captionBounds = await page.locator('.slideshow-tile figcaption').first().boundingBox();
        assert.ok(captionBounds.y >= cardBounds.y + cardBounds.height + 9, 'Label sits outside and below the entire card');
        const first = await page.locator('.slideshow-tile img').first().getAttribute('src');
        const second = await page.locator('.slideshow-tile img').nth(1).getAttribute('src');
        await page.getByRole('combobox', { name: 'Position of slide 2', exact: true }).selectOption('0');
        assert.equal(await page.locator('.slideshow-tile img').first().getAttribute('src'), second);
        assert.equal(await page.locator('#slideshow-restore').isVisible(), true);
        await page.getByRole('button', { name: 'Restore Changes', exact: true }).click();
        assert.equal(await page.locator('.slideshow-tile img').first().getAttribute('src'), first);
        assert.equal(await page.locator('#slideshow-restore').isVisible(), false);
        assert.equal(await page.locator('#slides-save-btn').isDisabled(), true);
        assert.equal(await page.getByRole('combobox', { name: 'Position of slide 1', exact: true }).inputValue(), '0');
        await page.getByRole('combobox', { name: 'Position of slide 1', exact: true }).selectOption({ value: '1' });
        await page.waitForFunction(src => document.querySelectorAll('.slideshow-tile img')[1].src === src, first);
        assert.equal(await page.locator('.slideshow-tile img').nth(1).getAttribute('src'), first);
        assert.equal(await page.locator('#slides-save-btn').isDisabled(), false);
        await page.getByRole('button', { name: 'Restore Changes', exact: true }).click();
        await page.getByRole('combobox', { name: 'Position of slide 2', exact: true }).selectOption('0');
        assert.equal(await page.evaluate(() => localStorage.getItem('sigma-custom-login-slides')), null);
        await page.getByRole('button', { name: 'Cancel', exact: true }).click();
        assert.equal(await page.locator('#slideshow-preview-image').getAttribute('src'), first);
        await page.getByRole('button', { name: 'Manage Slideshow' }).click();
        await page.locator('.slideshow-tile').first().dragTo(page.locator('.slideshow-tile').nth(2));
        assert.equal(await page.locator('.slideshow-tile img').nth(2).getAttribute('src'), first);
        await page.getByRole('button', { name: 'Save Changes' }).click();
        const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('sigma-custom-login-slides')));
        assert.equal(saved[2].src, first);
        await load();
        assert.equal(await page.locator('#slideshow-preview-image').getAttribute('src'), saved[0].src);
        await page.getByRole('button', { name: 'Manage Slideshow' }).click();
        await page.locator('[data-slide-mode="preview"]').click();
        assert.equal(await page.locator('#slideshow-grid').isVisible(), false);
        await page.getByRole('button', { name: 'Next slide', exact: true }).click();
        assert.equal(await page.locator('#slideshow-position').textContent(), '2 of 5');
        await page.getByRole('button', { name: 'Play slideshow', exact: true }).click();
        assert.equal(await page.getByRole('button', { name: 'Pause slideshow', exact: true }).count(), 1);
        await page.getByRole('button', { name: 'Pause slideshow', exact: true }).click();
        await page.locator('[data-slide-mode="grid"]').click();
        const data = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 60; c.height = 100; return c.toDataURL().split(',')[1]; });
        const file = { name: 'campus.png', mimeType: 'image/png', buffer: Buffer.from(data, 'base64') };
        await page.getByRole('button', { name: 'Add image', exact: true }).click();
        await page.locator('#slideshow-input').setInputFiles([file, { ...file, name: 'campus2.png' }]);
        await page.waitForFunction(() => document.querySelectorAll('.slideshow-tile').length === 7);
        assert.equal(await page.getByRole('button', { name: 'Add image', exact: true }).count(), 0);
        await page.getByRole('button', { name: 'Replace slide 1', exact: true }).click();
        await page.locator('#slideshow-input').setInputFiles(file);
        await page.waitForFunction(() => document.querySelector('.slideshow-tile img').src.startsWith('data:image/jpeg'));
        const proportions = await page.locator('.slideshow-tile img').first().evaluate(async image => { await image.decode(); return image.naturalWidth / image.naturalHeight; });
        assert.equal(proportions, 0.6);
        await page.getByRole('button', { name: 'Delete slide 7', exact: true }).click();
        assert.equal(await page.locator('.slideshow-tile').count(), 6);
        assert.equal(await page.getByRole('button', { name: 'Add image', exact: true }).isVisible(), true);
        await page.getByRole('button', { name: 'Add image', exact: true }).click();
        await page.locator('#slideshow-input').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') });
        await page.waitForFunction(() => document.getElementById('slideshow-feedback').textContent.includes('PNG'));
        for (const width of [1200, 600, 390, 320]) {
            await page.setViewportSize({ width, height: 1000 });
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            await page.screenshot({ path: path.join(os.tmpdir(), `sigma-slideshow-${width}.png`), fullPage: true });
        }
        await page.evaluate(() => {
            window.originalSlideshowSetItem = Storage.prototype.setItem;
            Storage.prototype.setItem = function () { throw new Error('Storage full'); };
        });
        await page.getByRole('button', { name: 'Save Changes' }).click();
        assert.match(await page.locator('#slideshow-feedback').textContent(), /Unable to save/);
        assert.equal(await page.locator('#slideshow-actions').isVisible(), true);
        assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('sigma-custom-login-slides'))), saved);
        await page.evaluate(() => { Storage.prototype.setItem = window.originalSlideshowSetItem; });
        // The actual login renderer consumes the saved order and preserves proportions.
        await page.evaluate(() => { const slider = document.createElement('div'); slider.id = 'slider'; document.body.append(slider); });
        const login = fs.readFileSync(path.join(root, 'js/index.js'), 'utf8');
        await page.addScriptTag({ content: login.slice(login.indexOf('    const SLIDER_CONFIG_DEFAULT ='), login.indexOf('    function createSlider(')) });
        assert.deepEqual(await page.locator('#slider img').evaluateAll(images => images.map(image => image.getAttribute('src'))), saved.map(slide => slide.src));
        assert.equal(await page.locator('#slider img').first().evaluate(image => image.style.objectFit), 'contain');
        console.log('Slideshow passed: compact view, grid/preview, drag/buttons order, cancel/save/reload, upload/replace/delete, limit, proportions and responsive layout.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
