const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..');
(async () => {
    const browser = await chromium.launch({ headless: true, channel: 'chrome' });
    try {
        const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
        const html = fs.readFileSync(path.join(root, 'admin.html'), 'utf8');
        const start = html.indexOf('<section id="settings-branding-view"');
        const body = html.slice(start, html.indexOf('<section id="settings-integrations-view"', start));
        await page.route('http://sigma.test/**', route => {
            const url = new URL(route.request().url());
            if (url.pathname.startsWith('/js/')) return route.fulfill({ contentType: 'application/javascript', body: fs.readFileSync(path.join(root, url.pathname.slice(1))) });
            if (url.pathname.startsWith('/image/')) return route.fulfill({ contentType: 'image/jpeg', body: fs.readFileSync(path.join(root, 'image/ICC Goals.jpeg')) });
            return route.fulfill({ contentType: 'text/html', body: '<img id="welcome-panel-admin-img" width="40"><img id="welcome-panel-student-img" width="40"><img id="welcome-panel-teacher-img" width="40">' + body });
        });
        await page.goto('http://sigma.test/admin.html');
        await page.addStyleTag({ path: path.join(root, 'css/forms.css') });
        await page.addStyleTag({ path: path.join(root, 'css/settings-view.css') });
        await page.addStyleTag({ content: '#settings-branding-view{display:block}' });
        await page.addScriptTag({ url: 'http://sigma.test/js/welcome-banner-settings.js' });
        const original = await page.locator('#welcome-panel-preview').getAttribute('src');
        assert.ok(original.endsWith('ICC%20Goals.jpeg'));
        assert.equal(await page.locator('#welcome-panel-save-btn').isVisible(), false);
        assert.equal((await page.locator('.welcome-banner-preview').boundingBox()).height, 220);
        assert.equal(await page.locator('#welcome-banner-library').isVisible(), false);
        assert.match(await page.locator('#brand-welcome-panel .sigma-panel-subtitle').textContent(), /administrator, teacher, and student/);
        const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 100; c.height = 60; return c.toDataURL().split(',')[1]; });
        const file = { name: 'banner.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') };
        await page.locator('#welcome-banner-change').click();
        assert.equal(await page.locator('.sigma-settings-sidebar').isVisible(), false);
        assert.equal(await page.locator('#brand-logos-panel').isVisible(), false);
        assert.equal(await page.locator('#brand-slides-panel').isVisible(), false);
        assert.equal(await page.locator('#welcome-banner-size').isVisible(), true);
        assert.match(await page.locator('#welcome-banner-size').textContent(), /220 px/);
        await page.locator('#welcome-panel-input').setInputFiles(file);
        await page.waitForFunction(() => !document.getElementById('welcome-panel-save-btn').disabled);
        assert.equal(await page.locator('#welcome-panel-admin-img').getAttribute('src'), original);
        await page.locator('#welcome-panel-cancel').click();
        assert.equal(await page.locator('#welcome-panel-preview').getAttribute('src'), original);
        assert.equal(await page.locator('.sigma-settings-sidebar').isVisible(), true);
        await page.locator('#welcome-banner-change').click();
        await page.locator('#welcome-panel-input').setInputFiles(file);
        await page.waitForFunction(() => !document.getElementById('welcome-panel-save-btn').disabled);
        await page.locator('#welcome-panel-save-btn').click();
        const saved = await page.evaluate(() => localStorage.getItem('sigma-welcome-panel'));
        assert.ok(saved.startsWith('data:image/jpeg'));
        assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('sigma-welcome-banner-library')).length), 1);
        for (const role of ['admin', 'student', 'teacher']) assert.equal(await page.locator(`#welcome-panel-${role}-img`).getAttribute('src'), saved);
        await page.locator('#welcome-banner-change').click();
        await page.locator('#welcome-banner-restore').click();
        assert.equal(await page.locator('#welcome-panel-preview').getAttribute('src'), original);
        assert.equal(await page.locator('#welcome-panel-admin-img').getAttribute('src'), saved);
        await page.locator('#welcome-panel-save-btn').click();
        assert.equal(await page.locator('#welcome-panel-admin-img').getAttribute('src'), original);
        await page.locator('#welcome-banner-change').click();
        const choice = page.getByRole('button', { name: 'Choose banner 1: banner.png', exact: true });
        await choice.click();
        assert.equal(await page.locator('#welcome-panel-preview').getAttribute('src'), saved);
        assert.equal(await page.locator('#welcome-panel-admin-img').getAttribute('src'), original);
        await page.locator('#welcome-panel-cancel').click();
        await page.locator('#welcome-banner-change').click();
        await page.locator('#welcome-panel-input').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') });
        assert.match(await page.locator('#welcome-banner-feedback').textContent(), /PNG/);
        for (const width of [1200, 600, 390, 320]) {
            await page.setViewportSize({ width, height: 900 });
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            const box = await page.locator('.welcome-banner-preview').boundingBox();
            const expectedHeight = width <= 768 ? Math.max(145, Math.min(width * 0.36, 175)) : 220;
            assert.ok(Math.abs(box.height - expectedHeight) < 1);
            const img = await page.locator('#welcome-panel-preview').boundingBox();
            assert.ok(img.height <= box.height && img.width <= box.width, 'Image stays within the actual banner frame');
            await page.locator('#brand-welcome-panel').screenshot({ path: path.join(os.tmpdir(), `sigma-welcome-banner-${width}.png`) });
        }
        console.log('Welcome banner passed: compact/isolated edit, draft upload, Cancel, shared Save, default restore, validation and responsive layout.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
