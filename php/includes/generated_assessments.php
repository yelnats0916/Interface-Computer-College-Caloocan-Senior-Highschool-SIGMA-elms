<?php
/** Shared server records for assessment history and the quiz editor. */
function sigmaGeneratedQuestions($raw): array {
    if (is_string($raw)) $raw = json_decode($raw, true);
    if (!is_array($raw)) return [];
    $questions = $raw['questions'] ?? $raw;
    return is_array($questions) && array_is_list($questions) ? $questions : [];
}

function sigmaGeneratedQuizFromLog(array $log): ?array {
    $questions = sigmaGeneratedQuestions($log['response'] ?? null);
    if (!$questions) return null;
    $generation = (string)($log['generationId'] ?? $log['id'] ?? '');
    if (!preg_match('/^ASMTG?-\d{4}-\d{4,}$/D', $generation)) return null;
    $title = preg_match('/about\s+(.+)$/i', $log['prompt'] ?? '', $match) ? $match[1] : 'AI Generated Assessment';
    return ['id'=>'ai-asmt-'.$generation, 'code'=>$generation, 'title'=>$title,
        'desc'=>'Generated by SIGMA AI.', 'questions'=>$questions, 'questionsCount'=>count($questions),
        'totalPoints'=>array_sum(array_column($questions, 'points')), 'isAi'=>true, 'source'=>'ai',
        'status'=>'draft', 'isDraft'=>true, 'authorId'=>(string)($log['userId'] ?? ''),
        'icon'=>'fa-bolt-lightning', 'color'=>'#15803d', 'createdAt'=>$log['timestamp'] ?? null];
}

/** Legacy generation URLs remain readable on a fresh browser, without local storage. */
function sigmaFindGeneratedQuiz(PDO $db, string $id, array $actor): ?array {
    $generation = preg_replace('/^ai-asmt-/', '', $id);
    if (!preg_match('/^ASMTG?-\d{4}-\d{4,}$/D', $generation)) return null;
    $existing = $db->prepare('SELECT id FROM quizzes WHERE id=? OR code=? LIMIT 1');
    $existing->execute(['ai-asmt-'.$generation, $generation]);
    if ($existing->fetchColumn()) return null; // A deleted or private saved quiz cannot be recovered through its log.
    $query = $db->prepare("SELECT user_id,payload FROM ai_logs WHERE id=? AND feature='quiz' AND is_deleted=0 LIMIT 1");
    $query->execute([$generation]);
    $row = $query->fetch(PDO::FETCH_ASSOC);
    $admin = in_array(strtolower($actor['role'] ?? ''), ['admin','masteradmin','administrator'], true);
    if (!$row || (!$admin && (string)$row['user_id'] !== (string)$actor['id'])) return null;
    return sigmaGeneratedQuizFromLog(json_decode($row['payload'], true) ?: []);
}

/** Keep the complete result even when its audit response exceeds the log size limit. */
function sigmaSaveGeneratedQuiz(PDO $db, string $owner, array $input, array $result, int $timestamp): void {
    $quiz = sigmaGeneratedQuizFromLog(['generationId'=>$result['generationId'], 'userId'=>$owner,
        'response'=>$result['questions'], 'prompt'=>'about '.($input['topic'] ?? 'AI Generated Assessment'),
        'timestamp'=>gmdate('c', $timestamp)]);
    if (!$quiz) throw new RuntimeException('Generated questions could not be saved.');
    $user = $db->prepare('SELECT full_name,first_name,last_name,role FROM users WHERE id=?');
    $user->execute([$owner]); $profile = $user->fetch(PDO::FETCH_ASSOC) ?: [];
    $insert = $db->prepare("INSERT IGNORE INTO quizzes(id,code,title,description,status,author_id,author_name,author_role,questions,total_questions,total_points,icon,color,is_ai,created_at) VALUES(?,?,?,?,'draft',?,?,?,?,?,?,?,?,1,?)");
    $insert->execute([$quiz['id'], $quiz['code'], mb_substr($quiz['title'],0,255), $quiz['desc'], $owner,
        ($profile['full_name'] ?? '') ?: trim(($profile['first_name'] ?? '').' '.($profile['last_name'] ?? '')),
        $profile['role'] ?? 'Teacher', json_encode($quiz['questions'],JSON_UNESCAPED_UNICODE|JSON_THROW_ON_ERROR),
        $quiz['questionsCount'], $quiz['totalPoints'], $quiz['icon'], $quiz['color'], gmdate('Y-m-d H:i:s',$timestamp)]);
}
